// keyGroup is a condition package slice rendered from a spec key list.
type keyGroup struct {
	name string
	doc  string
	keys []*spec.Key
}

func keyGroups() []keyGroup {
	listed := []*spec.Key{}
	for _, k := range spec.Keys {
		if !k.Unlisted {
			listed = append(listed, k)
		}
	}
	allAdmin := append(append([]*spec.Key{}, spec.CommonAdminKeys...), spec.AdminActionKeys...)
	return []keyGroup{
		{"JWTKeys", "JWTKeys - Supported JWT keys, non-exhaustive list please\n// expand as new claims are standardized.", spec.JWTKeys},
		{"AllSupportedKeys", "AllSupportedKeys - is list of all all supported keys.", listed},
		{"CommonKeys", "CommonKeys - is list of all common condition keys.", spec.CommonKeys},
		{"CommonAdminKeys", "CommonAdminKeys are the condition keys every admin action takes: they\n// describe the request and its principal, not what the action works on.", spec.CommonAdminKeys},
		{"AdminActionKeys", "AdminActionKeys are the condition keys that describe what one kind of admin\n// action works on, such as the policy it names. The policy package lists which\n// actions take each of them.", spec.AdminActionKeys},
		{"AllSupportedAdminKeys", "AllSupportedAdminKeys - is list of all admin supported keys.", allAdmin},
		{"AllSupportedSTSKeys", "AllSupportedSTSKeys is the all supported conditions for STS policies", spec.AllSupportedSTSKeys},
	}
}

// actionName is one constant the generated code declares: an action or an
// alias of one.
type actionName struct {
	full      string
	goName    string
	goType    string
	canonical string
	action    *spec.Action
	ns        *spec.Namespace
}

type registry struct {
	names  map[string]*actionName
	byNS   map[string][]*actionName
	nsByID map[string]*spec.Namespace
	goType map[string]string
}

func goNameOf(ns *spec.Namespace, a *spec.Action, name string) string {
	if name == a.Name && a.GoName != "" {
		return a.GoName
	}
	return fmt.Sprintf(ns.GoNameFormat, name)
}

func buildRegistry() (*registry, error) {
	r := &registry{
		names:  map[string]*actionName{},
		byNS:   map[string][]*actionName{},
		nsByID: map[string]*spec.Namespace{},
		goType: map[string]string{},
	}
	for _, o := range outputs {
		for _, p := range o.prefixes {
			r.goType[p] = o.goType
		}
	}
	goNames := map[string]string{}
	for _, ns := range spec.Namespaces {
		if r.nsByID[ns.Prefix] != nil {
			return nil, fmt.Errorf("namespace %s declared twice", ns.Prefix)
		}
		if r.goType[ns.Prefix] == "" {
			return nil, fmt.Errorf("namespace %s has no generated output", ns.Prefix)
		}
		r.nsByID[ns.Prefix] = ns
		for i := range ns.Actions {
			a := &ns.Actions[i]
			full := ns.Prefix + ":" + a.Name
			for _, n := range append([]string{a.Name}, a.Aliases...) {
				an := &actionName{
					full:      ns.Prefix + ":" + n,
					goName:    goNameOf(ns, a, n),
					goType:    r.goType[ns.Prefix],
					canonical: full,
					action:    a,
					ns:        ns,
				}
				if r.names[an.full] != nil {
					return nil, fmt.Errorf("action %s declared twice", an.full)
				}
				if prev, ok := goNames[an.goName]; ok {
					return nil, fmt.Errorf("constant %s names both %s and %s", an.goName, prev, an.full)
				}
				goNames[an.goName] = an.full
				r.names[an.full] = an
				r.byNS[ns.Prefix] = append(r.byNS[ns.Prefix], an)
			}
		}
	}
	for _, an := range r.names {
		for _, imp := range an.action.Implies {
			if r.names[imp] == nil {
				return nil, fmt.Errorf("%s implies unknown action %s", an.full, imp)
			}
		}
	}
	return r, nil
}

// names returns the canonical name of an action followed by its aliases.
func (r *registry) group(full string) []*actionName {
	an := r.names[full]
	ns := an.ns
	out := []*actionName{r.names[an.canonical]}
	for _, alias := range an.action.Aliases {
		out = append(out, r.names[ns.Prefix+":"+alias])
	}
	return out
}

// ref renders a constant as an Action.
func (an *actionName) ref() string {
	if an.goType == "Action" {
		return an.goName
	}
	return "Action(" + an.goName + ")"
}

func resourceOf(ns *spec.Namespace, a *spec.Action) spec.Resource {
	if a.Resource != spec.ResourceUnspecified {
		return a.Resource
	}
	return ns.Resource
}

func writeDoc(w *bytes.Buffer, indent, goName, desc, fallback string) {
	desc = strings.TrimSpace(desc)
	if desc == "" {
		desc = fallback
	}
	lines := strings.Split(desc, "\n")
	sep := " - "
	if r := []rune(lines[0]); len(r) > 0 && unicode.IsLower(r[0]) {
		sep = " "
	}
	fmt.Fprintf(w, "%s// %s%s%s\n", indent, goName, sep, lines[0])
	for _, l := range lines[1:] {
		if l == "" {
			fmt.Fprintf(w, "%s//\n", indent)
			continue
		}
		fmt.Fprintf(w, "%s// %s\n", indent, l)
	}
}

func keyRef(k *spec.Key) string {
	return "condition." + k.GoName
}

// sameKeys reports whether two spec lists are the same list.
func sameKeys(a, b []*spec.Key) bool {
	return len(a) == len(b) && len(a) > 0 && &a[0] == &b[0]
}

func baseRef(base []*spec.Key) (string, error) {
	for _, g := range []struct {
		name string
		keys []*spec.Key
	}{
		{"condition.CommonKeys", spec.CommonKeys},
		{"condition.CommonAdminKeys", spec.CommonAdminKeys},
		{"condition.AllSupportedSTSKeys", spec.AllSupportedSTSKeys},
	} {
		if sameKeys(base, g.keys) {
			return g.name, nil
		}
	}
	if len(base) == 0 {
		return "nil", nil
	}
	return "", fmt.Errorf("base keys are not a condition package group")
}

func renderPolicyFile(r *registry, o output) ([]byte, error) {
	var w bytes.Buffer
	w.WriteString(header)
	w.WriteString("package policy\n\n")
	if o.keyMapVar != "" {
		w.WriteString("import \"github.com/minio/pkg/v3/policy/condition\"\n\n")
	}

	w.WriteString("const (\n")
	first := true
	for _, p := range o.prefixes {
		for _, an := range r.byNS[p] {
			if !first {
				w.WriteString("\n")
			}
			first = false
			if an.full == an.canonical {
				writeDoc(&w, "\t", an.goName, an.action.Desc, "the "+an.full+" action.")
			} else {
				fmt.Fprintf(&w, "\t// %s is an alias of %s.\n", an.goName, r.names[an.canonical].goName)
			}
			fmt.Fprintf(&w, "\t%s %s = %q\n", an.goName, o.goType, an.full)
		}
	}
	w.WriteString(")\n\n")

	fmt.Fprintf(&w, "// %s\nvar %s = map[%s]struct{}{\n", o.supportedDoc, o.supportedVar, o.goType)
	for _, p := range o.prefixes {
		for _, an := range r.byNS[p] {
			if !an.action.Unsupported {
				fmt.Fprintf(&w, "\t%s: {},\n", an.goName)
			}
		}
	}
	w.WriteString("}\n")

	if o.keyMapVar != "" {
		fmt.Fprintf(&w, "\n// %s\nvar %s = %s{\n", o.keyMapDoc, o.keyMapVar, o.keyMapType)
		for _, p := range o.prefixes {
			ns := r.nsByID[p]
			base, err := baseRef(ns.BaseKeys)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", p, err)
			}
			for _, an := range r.byNS[p] {
				if an.action.Unsupported {
					continue
				}
				fmt.Fprintf(&w, "\t%s: newActionKeySet(%s", an.ref(), base)
				for _, k := range an.action.Keys {
					fmt.Fprintf(&w, ", %s", keyRef(k))
				}
				w.WriteString("),\n")
			}
		}
		w.WriteString("}\n")
	}

	switch o.goType {
	case "Action":
		w.WriteString("\n// SupportedObjectActions - list of all supported object actions.\nvar SupportedObjectActions = map[Action]struct{}{\n")
		for _, p := range o.prefixes {
			ns := r.nsByID[p]
			for _, an := range r.byNS[p] {
				res := resourceOf(ns, an.action)
				if !an.action.Unsupported && (res == spec.ResourceObject || res == spec.ResourceBucketOrObject) {
					fmt.Fprintf(&w, "\t%s: {},\n", an.goName)
				}
			}
		}
		w.WriteString("}\n")
	case "AdminAction":
		w.WriteString("\n// AdminActionsWithResource - admin actions that are\n// related to a resource and needs to be explicitly specified\n// in the policy.\nvar AdminActionsWithResource = map[AdminAction]struct{}{\n")
		for _, p := range o.prefixes {
			ns := r.nsByID[p]
			for _, an := range r.byNS[p] {
				if !an.action.Unsupported && resourceOf(ns, an.action) == spec.ResourceBucket {
					fmt.Fprintf(&w, "\t%s: {},\n", an.goName)
				}
			}
		}
		w.WriteString("}\n")
	}
	return format.Source(w.Bytes())
}

func renderActionSetFile(r *registry) ([]byte, error) {
	var w bytes.Buffer
	w.WriteString(header)
	w.WriteString("package policy\n\n")

	w.WriteString("// implicitActions maps every name of an action to the actions a statement\n// naming it also matches.\nvar implicitActions = map[Action]ActionSet{\n")
	for _, ns := range spec.Namespaces {
		for _, an := range r.byNS[ns.Prefix] {
			if len(an.action.Implies) == 0 {
				continue
			}
			var implied []string
			for _, imp := range an.action.Implies {
				for _, g := range r.group(imp) {
					implied = append(implied, g.ref())
				}
			}
			fmt.Fprintf(&w, "\t%s: NewActionSet(%s),\n", an.ref(), strings.Join(implied, ", "))
		}
	}
	w.WriteString("}\n\n")

	w.WriteString("// actionAliases maps every name of an action that has aliases to its other\n// names.\nvar actionAliases = map[Action][]Action{\n")
	for _, ns := range spec.Namespaces {
		for _, an := range r.byNS[ns.Prefix] {
			if len(an.action.Aliases) == 0 {
				continue
			}
			var others []string
			for _, g := range r.group(an.full) {
				if g.full != an.full {
					others = append(others, g.ref())
				}
			}
			fmt.Fprintf(&w, "\t%s: {%s},\n", an.ref(), strings.Join(others, ", "))
		}
	}
	w.WriteString("}\n\n")

	w.WriteString("// hasActionAliases reports whether action is a key of actionAliases. A switch\n// rejects the common case of no aliases faster than a map lookup.\nfunc hasActionAliases(action Action) bool {\n\tswitch action {\n\tcase ")
	var cases []string
	for _, ns := range spec.Namespaces {
		for _, an := range r.byNS[ns.Prefix] {
			if len(an.action.Aliases) > 0 {
				cases = append(cases, an.ref())
			}
		}
	}
	if len(cases) == 0 {
		cases = []string{`""`}
	}
	w.WriteString(strings.Join(cases, ",\n\t\t"))
	w.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n")
	return format.Source(w.Bytes())
}

func renderConditionFile() ([]byte, error) {
	var w bytes.Buffer
	w.WriteString(header)
	w.WriteString("package condition\n\n")

	seen := map[string]bool{}
	w.WriteString("// Condition key names.\nconst (\n")
	for i, k := range spec.Keys {
		if k.GoName == "" {
			return nil, fmt.Errorf("key %s has no GoName", k.Name)
		}
		if seen[k.Name] {
			return nil, fmt.Errorf("key %s declared twice", k.Name)
		}
		seen[k.Name] = true
		if i > 0 {
			w.WriteString("\n")
		}
		writeDoc(&w, "\t", k.GoName, k.Desc, "the "+k.Name+" condition key.")
		fmt.Fprintf(&w, "\t%s KeyName = %q\n", k.GoName, k.Name)
	}
	w.WriteString(")\n")

	for _, g := range keyGroups() {
		fmt.Fprintf(&w, "\n// %s\nvar %s = []KeyName{\n", g.doc, g.name)
		for _, k := range g.keys {
			if !seen[k.Name] {
				return nil, fmt.Errorf("%s lists undeclared key %s", g.name, k.Name)
			}
			fmt.Fprintf(&w, "\t%s,\n", k.GoName)
		}
		w.WriteString("}\n")
	}

	w.WriteString("\n// toTrim lists the prefixes to trim from key names.\nvar toTrim = map[string]bool{\n")
	for _, p := range spec.KeyPrefixes {
		if p.Trim {
			fmt.Fprintf(&w, "\t%s: true,\n", strconv.Quote(p.Name))
		}
	}
	w.WriteString("}\n")

	w.WriteString("\n// untrimmedKeys read the request value named by their whole key, prefix\n// included, because trimming would collide with a key that carries a\n// different value.\nvar untrimmedKeys = map[KeyName]bool{\n")
	for _, k := range spec.Keys {
		if k.Untrimmed {
			fmt.Fprintf(&w, "\t%s: true,\n", k.GoName)
		}
	}
	w.WriteString("}\n")

	w.WriteString("\n// variableKeys are the keys that take a /<variable> suffix naming the tag they\n// test, as in s3:ExistingObjectTag/<tag>. Every other key names one value.\nvar variableKeys = map[KeyName]bool{\n")
	for _, k := range spec.Keys {
		if k.Variable {
			fmt.Fprintf(&w, "\t%s: true,\n", k.GoName)
		}
	}
	w.WriteString("}\n")
	return format.Source(w.Bytes())
}

// render returns every generated file, keyed by its path relative to the
// policy package directory.
func render() (map[string][]byte, error) {
	r, err := buildRegistry()
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	for _, o := range outputs {
		src, err := renderPolicyFile(r, o)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", o.file, err)
		}
		files[o.file] = src
	}
	src, err := renderActionSetFile(r)
	if err != nil {
		return nil, fmt.Errorf("actionset_gen.go: %w", err)
	}
	files["actionset_gen.go"] = src
	src, err = renderConditionFile()
	if err != nil {
		return nil, fmt.Errorf("condition/keyname_gen.go: %w", err)
	}
	files["condition/keyname_gen.go"] = src
	return files, nil
}

func sortedPaths(files map[string][]byte) []string {
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	return paths
}
